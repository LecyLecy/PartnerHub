import assert from "node:assert/strict";
import { createRequire } from "node:module";
import { mkdir } from "node:fs/promises";
const require = createRequire(import.meta.url);
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || "playwright");
const base = process.env.UI_BASE_URL || "http://127.0.0.1:3132";
const browser = await chromium.launch({ channel: "msedge", headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
const errors = [];
page.on("pageerror", error => errors.push(error.message));
page.on("dialog", dialog => dialog.accept());
const go = route => page.goto(base + route, { waitUntil: "networkidle" });
const noDraft = async () => assert.doesNotMatch(await page.locator("body").innerText(), /draft|salinan lokal|tersimpan di browser/i);
try {
  await go("/guide");
  await page.evaluate(() => {
    localStorage.setItem("partnerhub:event-draft:v1", JSON.stringify({ version: 1, draft: { title: "Old browser copy" } }));
    sessionStorage.setItem("partnerhub:register-draft:v1", JSON.stringify({ version: 1, role: "user", step: 0, values: { fullName: "Old signup copy" } }));
  });
  await page.getByLabel("Ganti peran demo", { exact: true }).selectOption("organizer");
  await page.waitForURL("**/organizer");
  await noDraft();
  await go("/events/new");
  await noDraft();
  assert.equal(await page.locator('input[name="title"]').inputValue(), "");
  const countEvents = () => page.evaluate(() => JSON.parse(sessionStorage.getItem("partnerhub:demo:v3")).events.length);
  const before = await countEvents();
  await page.locator('input[name="title"]').fill("Unsaved event");
  await page.getByRole("checkbox", { name: "Pendidikan", exact: true }).check();
  await page.getByRole("button", { name: "Lanjutkan", exact: true }).click();
  await page.getByRole("button", { name: "Kembali", exact: true }).click();
  assert.equal(await page.locator('input[name="title"]').inputValue(), "Unsaved event");
  await page.reload({ waitUntil: "networkidle" });
  assert.equal(await page.locator('input[name="title"]').inputValue(), "");
  assert.equal(await countEvents(), before, "Unsaved forms never create events");
  await page.getByRole("button", { name: "Modul event", exact: false }).click();
  await page.getByRole("button", { name: "Selesai susunan", exact: true }).click();
  await page.locator('input[name="title"][aria-invalid="true"]').waitFor();
  assert.equal(await countEvents(), before, "Incomplete forms cannot be saved");
  await mkdir(".impeccable/no-draft", { recursive: true });
  await go("/events/new");
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.waitForTimeout(400);
  await page.screenshot({ path: ".impeccable/no-draft/create-desktop.png", fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.waitForTimeout(400);
  await noDraft();
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await page.screenshot({ path: ".impeccable/no-draft/create-mobile.png", fullPage: true });
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.locator('input[name="title"]').fill("No draft regression");
  await page.getByRole("checkbox", { name: "Pendidikan", exact: true }).check();
  await page.getByRole("button", { name: "Lanjutkan", exact: true }).click();
  const day = new Date(Date.now() + 14 * 86400000).toISOString().slice(0, 10);
  for (const [field, value] of Object.entries({ date: day, startTime: "09:00", endTime: "12:00", venue: "Ruang kolaborasi", capacity: "100" })) {
    await page.locator('input[name="' + field + '"]').fill(value);
  }
  await page.getByRole("button", { name: "Lanjutkan", exact: true }).click();
  await page.locator('input[name="organizationName"]').fill("Komunitas Uji");
  await page.getByRole("button", { name: "Lanjutkan", exact: true }).click();
  await page.getByRole("button", { name: "Selesai susunan", exact: true }).click();
  await page.waitForURL(/\/organizer\/archive\?created=/);
  await noDraft();
  assert.equal(await countEvents(), before + 1);
  const eventPath = "/events/" + new URL(page.url()).searchParams.get("created");
  await go(eventPath + "/edit");
  await page.locator('input[name="title"]').fill("Updated event regression");
  await page.getByRole("button", { name: "Modul event", exact: false }).click();
  await page.getByRole("button", { name: "Simpan perubahan", exact: true }).click();
  await page.waitForURL(/\?saved=1/);
  await page.getByRole("heading", { name: "Updated event regression", exact: true }).waitFor();
  assert.equal(await countEvents(), before + 1, "Editing does not duplicate events");
  await noDraft();
  const account = await browser.newPage();
  account.on("dialog", dialog => dialog.accept());
  await account.goto(base + "/register?role=user", { waitUntil: "networkidle" });
  const name = account.getByLabel("Nama lengkap", { exact: false });
  await name.fill("Temporary Signup");
  await account.reload({ waitUntil: "networkidle" });
  assert.equal(await name.inputValue(), "");
  assert.equal(await account.evaluate(() => sessionStorage.getItem("partnerhub:register-draft:v1")), null);
  await account.close();
  assert.deepEqual(errors, []);
  console.log("PASS: no draft UI, no local copy restore, in-memory Back, reload clears form, no incomplete save, create/edit without duplicates, mobile layout, signup reload.");
} finally { await browser.close(); }
